// ===== INSTRUMENTATION: metrics tracked during A* and along the solution path =====
struct SearchMetrics
{
    double solver_time = 0.0;          // seconds
    int movements = 0;                 // solution length (moves)
    long expanded = 0;                 // expanded nodes (= closed list size at goal)
    long real_total = 0;               // successors generated by expanded nodes (A* BF numerator)
    long eff_total = 0;                // successors that are new states (A* Effective BF numerator)
    long repeated = 0;                 // successors already generated before
    long reopened = 0;                 // closed nodes re-inserted in open
    long open_list = 0;                // final size of the open list
    long closed_list = 0;              // final size of the closed list
    int real_min = -1, real_max = -1;  // min/max successors per expanded node
    int eff_min = -1, eff_max = -1;    // min/max new successors per expanded node
    // solution path (states from the initial state to the one before the goal)
    long sol_real_total = 0, sol_eff_total = 0, sol_repeated = 0;
    int sol_real_min = -1, sol_real_max = -1, sol_eff_min = -1, sol_eff_max = -1;
    bool solved = false;
    // structural features of the initial board (3x3 slots, row-major; exit below slot 7)
    int A1_ship_exit_distance = 0;     // Manhattan distance ship -> exit slot (7)
    int A2_exit_blockers = 0;          // occupied slots of the exit column below the ship
    int A3_empty_ship_distance = 0;    // Manhattan distance empty slot -> ship
    int A4_asteroids_around_ship = 0;  // large asteroids (B, C) orthogonally adjacent to the ship
};
